"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const html=fs.readFileSync(path.join(root,"rpe-v2/index.html"),"utf8");
const css=fs.readFileSync(path.join(root,"rpe-v2/customer-pro.css"),"utf8");
const sw=fs.readFileSync(path.join(root,"rpe-v2/rpe-v2-sw.js"),"utf8");
const critical=html.match(/<style id="rnv-checkout-critical">([\s\S]*?)<\/style>/);
assert.ok(critical,"Checkout requires inline critical CSS to survive WebView stylesheet failures");
assert.match(html,/id="rnv-customer-main-styles"[^>]*href=|href="\.\/customer-pro\.css\?v=20261103-checkout-layout" id="rnv-customer-main-styles"/);
assert.match(critical[1],/#marketCheckoutOverlay\.show\{display:flex\}/,"Checkout must be a modal overlay");
assert.match(critical[1],/#marketCheckoutOverlay \.rnv-checkout-card\{[^}]*width:min\(100%,620px\)/,"Checkout card must fit the viewport");
assert.match(critical[1],/#marketCheckoutOverlay \.rnv-checkout-fields\{[^}]*display:grid/,"Fields require a grid layout");
assert.match(critical[1],/@media\(max-width:520px\)/,"Narrow phones need single-column fields");
assert.match(critical[1],/#marketCheckoutOverlay \.rnv-checkout-fields label\.full\{grid-column:auto\}/,"Full-width fields must not overflow on mobile");
assert.match(critical[1],/#marketCheckoutOverlay \.rnv-checkout-fields input,#marketCheckoutOverlay \.rnv-checkout-fields select,#marketCheckoutOverlay \.rnv-checkout-fields textarea\{[^}]*box-sizing:border-box/,"Inputs must not overflow");
assert.match(critical[1],/#marketCheckoutOverlay \.rnv-checkout-place\{[^}]*width:100%/,"Checkout action must be a proper full-width button");
assert.match(critical[1],/#marketCheckoutOverlay \.rnv-checkout-head button\{[^}]*border-radius:50%/,"Close control must be styled");
assert.match(css,/\.rnv-checkout-overlay\.show\{display:flex\}/,"Complete checkout stylesheet remains present");
assert.match(sw,/ranova-rpe-v2-shell-v95/);
assert.match(sw,/customer-pro\.css\?v=20261103-checkout-layout/);
assert.match(html,/id="marketCheckoutPlace"/,"Order placement must remain attached to checkout");
console.log("PASS checkout styling: critical CSS, mobile layout, controls, offline cache");
