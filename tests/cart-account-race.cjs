"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const src=fs.readFileSync(path.join(__dirname,"../rpe-v2/app.js"),"utf8");
assert.match(src,/async function loadAll\(\)\{[\s\S]*?if\(user\?\.id!==uid\)return;[\s\S]*?profile=prof\.data/);
assert.match(src,/\.then\(\(\[fav,marketFav,rec,noti,addr,ret\]\)=>\{\s*if\(user\?\.id!==uid\)return;/);
const fn=src.match(/async function loadCartItems\(\)\{[\s\S]*?\n\}/);
assert.ok(fn,"Legacy cart loader exists");
const deferred=()=>{let resolve;const promise=new Promise(r=>resolve=r);return {promise,resolve}};
(async()=>{
 const request=deferred();
 const context={user:{id:"buyer-A"},cartId:"cart-A",cartItems:[{id:"original"}],sb:{from:()=>({select:()=>({eq:()=>({order:()=>({limit:()=>request.promise})})})})}};
 vm.createContext(context);
 vm.runInContext(fn[0]+"\nthis.run=loadCartItems",context);
 const pending=context.run();
 context.user={id:"buyer-B"};context.cartId="cart-B";context.cartItems=[];
 request.resolve({data:[{id:"buyer-A-private-item"}],error:null});
 await pending;
 assert.deepEqual(context.cartItems,[],"Stale response must not populate buyer B's cart");
 const second=deferred();
 context.sb={from:()=>({select:()=>({eq:()=>({order:()=>({limit:()=>second.promise})})})})};
 const current=context.run();
 second.resolve({data:[{id:"buyer-B-item"}],error:null});
 await current;
 assert.equal(context.cartItems[0].id,"buyer-B-item","Current buyer should still load cart");
 console.log("PASS cart account-switch race and valid buyer load");
})().catch(e=>{console.error(e);process.exitCode=1});
